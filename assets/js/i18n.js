  /* ── Apply translations to DOM ── */
  function applyLang(lang) {
    if (!T[lang]) return;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      if (T[lang][key] !== undefined) el.innerHTML = T[lang][key];
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-ph');
      if (T[lang][key] !== undefined) el.placeholder = T[lang][key];
    });
    /* sync select option text for service dropdown */
    document.querySelectorAll('[data-i18n-opt]').forEach(function (el) {
      var key = el.getAttribute('data-i18n-opt');
      if (T[lang][key] !== undefined) el.textContent = T[lang][key];
    });
    document.documentElement.lang = lang;
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
    localStorage.setItem('ga_lang', lang);
  }

  /* ── Build and inject the flag switcher ── */
  function makeSwitcher(extraClass) {
    var sw = document.createElement('div');
    sw.className = 'lang-switcher' + (extraClass ? ' ' + extraClass : '');
    sw.innerHTML =
      '<button class="lang-btn" data-lang="en" aria-label="Switch to English">' +
        '<span aria-hidden="true">\uD83C\uDDEC\uD83C\uDDE7</span> EN' +
      '</button>' +
      '<button class="lang-btn" data-lang="fr" aria-label="Passer en fran\u00e7ais">' +
        '<span aria-hidden="true">\uD83C\uDDEB\uD83C\uDDF7</span> FR' +
      '</button>';
    return sw;
  }

  function initSwitcher() {
    /* Desktop nav — insert before hamburger */
    var navInner = document.querySelector('.nav-inner');
    if (navInner) {
      var sw = makeSwitcher();
      var hamburger = navInner.querySelector('.hamburger');
      hamburger ? navInner.insertBefore(sw, hamburger) : navInner.appendChild(sw);
    }
    /* Mobile menu — append at bottom */
    var mobileMenu = document.querySelector('.mobile-menu');
    if (mobileMenu) {
      mobileMenu.appendChild(makeSwitcher('lang-switcher--mobile'));
    }
    /* Attach click handlers (covers both nav + mobile) */
    document.querySelectorAll('.lang-btn').forEach(function (btn) {
      btn.addEventListener('click', function () {
        applyLang(btn.getAttribute('data-lang'));
      });
    });
  }

